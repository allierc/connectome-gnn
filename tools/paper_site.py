def paper_items():
    """Every labelled figure and table of main.tex, in order: label, kind, number (main.aux), page, files."""
    aux = open(os.path.join(PAPER, "main.aux")).read()
    num, page = {}, {}
    for lab, n, pg in re.findall(r"\\newlabel\{((?:fig|tab):[^}]*)\}\{\{([^}]*)\}\{(\d+)\}", aux):
        num[lab], page[lab] = n, int(pg)
    tex = open(os.path.join(PAPER, "main.tex")).read()
    found = []
    for m in re.finditer(r"\\begin\{(figure|table)\}.*?\\end\{\1\}", tex, re.S):
        blk = m.group(0)
        lab = re.search(r"\\label\{([^}]*)\}", blk)
        found.append((m.start(), lab.group(1) if lab else None,
                      re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]*)\}", blk)))
    for m in re.finditer(r"\\input\{(tables/[^}]*)\}", tex):
        f = os.path.join(PAPER, m.group(1) + ("" if m.group(1).endswith(".tex") else ".tex"))
        lab = re.search(r"\\label\{([^}]*)\}", open(f).read()) if os.path.exists(f) else None
        found.append((m.start(), lab.group(1) if lab else None, [m.group(1)]))
    appx = tex.index("\\appendix")
    items = []
    for pos, lab, files in sorted(found):
        if not lab or lab not in num:
            continue
        fig = lab.startswith("fig")
        supp = pos > appx
        items.append({"label": lab, "fig": fig, "supp": supp, "num": num[lab], "page": page[lab], "files": files,
                      "short": ("Supp. " if supp else "") + ("Fig. " if fig else "Tab. ") + num[lab],
                      "caption_key": ("Supplementary " if supp else "") + ("Figure " if fig else "Table ") + num[lab] + ":"})
    return items


def caption_and_page(doc, item):
    """The caption's first block of text and its page index in main.pdf (searched around the aux page)."""
    for pi in [item["page"] - 1, item["page"], item["page"] - 2, item["page"] + 1]:
        if not 0 <= pi < doc.page_count:
            continue
        pg = doc[pi]
        for b in pg.get_text("blocks"):
            txt = " ".join(b[4].split())
            if txt.startswith(item["caption_key"]):
                return txt[len(item["caption_key"]):].strip(), pi, b
    return "", None, None


