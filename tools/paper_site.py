def permalinks(man):
    gh, branch = man["github"], man.get("branch", "main")
    sha = subprocess.run(["git", "-C", ROOT, "rev-parse", f"origin/{branch}"], capture_output=True, text=True).stdout.strip()
    links = {}
    for key, c in man["code"].items():
        txt = subprocess.run(["git", "-C", ROOT, "show", f"{sha}:{c['file']}"], capture_output=True, text=True)
        n = None
        if txt.returncode == 0:
            for i, line in enumerate(txt.stdout.split("\n"), 1):
                if re.search(c["find"], line):
                    n = i
                    break
        links[key] = {"name": c["name"], "url": f"{gh}/blob/{sha}/{c['file']}" + (f"#L{n}" if n else ""),
                      "pushed": txt.returncode == 0}
    return sha, links


