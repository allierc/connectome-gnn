def figure_png(item, manifest_item, img_dir):
    if manifest_item and manifest_item.get("figure"):
        return os.path.join(PAPER, manifest_item["figure"] + ".png")
    f = os.path.join(PAPER, item["files"][0]) if item["files"] else None
