_TEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
        "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "±": r"$\pm$", "→": r"$\to$",
        "−": "-", "–": "--", "—": "---", "σ": r"$\sigma$", "γ": r"$\gamma$", "τ": r"$\tau$", "φ": r"$\phi$",
        "θ": r"$\theta$", "μ": r"$\mu$", "α": r"$\alpha$", "β": r"$\beta$", "λ": r"$\lambda$",
        "≥": r"$\geq$", "≤": r"$\leq$", "×": r"$\times$", "∼": r"$\sim$", "≈": r"$\approx$", "·": r"$\cdot$",
        "’": "'", "‘": "`", "“": "``", "”": "''", "…": "...", "ˆ": "", "∈": r"$\in$", "²": r"$^2$",
        "°": r"$^\circ$", "µ": r"$\mu$", "Δ": r"$\Delta$", "ϕ": r"$\phi$", "∗": "*"}


def tex(s):
    """LaTeX-safe text: one pass over the characters; anything else outside Latin-1 is dropped."""
    out = []
    for ch in str(s):
        if ch in _TEX:
            out.append(_TEX[ch])
        elif ord(ch) < 256:
            out.append(ch)
    return "".join(out)


def rows_tex(d):
    return "\n".join(rf"\textcolor{{gray}}{{{tex(k)}}} & {tex(v)} \\" for k, v in d.items())


def links_tex(links):
    # '#' (the GitHub line anchor) must be \# inside a beamer frame, which reads its body as an argument
    return r"\\ ".join(rf"\href{{{u.replace('#', chr(92) + '#')}}}{{\textcolor{{cyan}}{{{tex(n)}}}}}" for n, u in links)


def frame(title, left, right, src="", target=""):
    return (rf"""\begin{{frame}}{{{title}}}""" + (rf"\hypertarget{{{target}}}{{}}" if target else "") + rf"""
\begin{{columns}}[T]
\begin{{column}}{{0.57\textwidth}}
{left}
\end{{column}}
\begin{{column}}{{0.41\textwidth}}
\fitcol{{{right}}}
\end{{column}}
\end{{columns}}
""" + (rf"\srcpath{{{tex(src)}}}" + "\n" if src else "") + r"\end{frame}" + "\n")


def frame_one(title, body, src="", target=""):
    return (rf"""\begin{{frame}}{{{title}}}""" + (rf"\hypertarget{{{target}}}{{}}" if target else "") + rf"""
\vspace{{2pt}}{{\centering
{body}
\par}}
""" + (rf"\srcpath{{{tex(src)}}}" + "\n" if src else "") + r"\end{frame}" + "\n")


def right_col(head, description, facts, links, table=""):
    out = [rf"{{\small\textbf{{{tex(head)}}}}}\\[3pt]"] if head else []
    if description:
        out.append(rf"{{\footnotesize {tex(description)}}}\\[6pt]")
    if facts:
        out.append(r"{\scriptsize\begin{tabular}{@{}p{0.30\linewidth}p{0.66\linewidth}@{}}" + rows_tex(facts) + r"\end{tabular}}\\[6pt]")
    if table:
        out.append(table + r"\\[6pt]")
    if links:
        out.append(r"{\scriptsize\textcolor{gray}{code on GitHub}\\ " + links_tex(links) + "}")
    return "\n".join(out)


def metrics_table_tex(head, rows):
    keep = [h for h in head if h and any(r.get(h, "").strip() for r in rows)]
    out = [r"\resizebox{\textwidth}{!}{\fontsize{7}{8.5}\selectfont\setlength{\tabcolsep}{2pt}\begin{tabular}{" + "l" * len(keep) + "}",
           " & ".join(rf"\textbf{{{tex(h)}}}" for h in keep) + r" \\ \hline"]
    for r in rows:
        out.append(" & ".join(tex(r.get(h, "")) for h in keep) + r" \\")
    out.append(r"\end{tabular}}")
    return "\n".join(out)


