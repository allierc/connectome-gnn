# --------------------------------------------------------------------------- 8. build
def build(only=None, force=False, use_agent=True):
    import fitz
    man = yaml.safe_load(open(os.path.join(SITE, "items.yaml")))
    items = paper_items()
    if only:
        items = [it for it in items if it["label"] in only]
    used = {s["experiment"] for it in items for s in (man["items"].get(it["label"]) or {}).get("sections", [])
            if s.get("experiment")}
    used_runs = {r for it in items for s in (man["items"].get(it["label"]) or {}).get("sections", [])
                 if s.get("experiment") for r in section_runs(s)}
    st, problems = check_sync(used, used_runs, force)
    sha, links = permalinks(man)
    for k, v in links.items():
        if not v["pushed"]:
            print(f"WARNING code link {k}: {man['code'][k]['file']} not in origin/{man.get('branch', 'main')}")
    for d in ("slides", "img"):
        os.makedirs(os.path.join(OUT, d), exist_ok=True)
    paper = fitz.open(os.path.join(PAPER, "main.pdf"))
    report = fitz.open(os.path.join(EXP_DIR, "report.pdf"))
    img_dir = os.path.join(OUT, "img")

    # captions, images and the agent's descriptions (in parallel: one claude call per item and section)
    jobs = []
    for it in items:
        mi = man["items"].get(it["label"])
        it["caption"], it["pi"], it["cap_block"] = caption_and_page(paper, it)
        it["m"] = mi
        if mi:
            jobs.append((it, None))
            for s in mi.get("sections", []):
                if s.get("experiment"):
                    jobs.append((it, s))

    def _desc(job):
        it, s = job
        facts = section_facts(s) if s else item_facts(it["m"])
        cap = it["caption"] if s is None else f"{it['caption'][:300]} SECTION: {s['name']}"
        return job, facts, describe(cap, facts, use_agent)

    results = {}
    with cf.ThreadPoolExecutor(6) as ex:
        for (it, s), facts, d in ex.map(_desc, jobs):
            results[(it["label"], s["name"] if s else None)] = (facts, d)

    slides, rules = [], []
    for it in items:
        mi = it["m"]
        tag = re.sub(r"\W+", "_", it["label"])
        title_short = short_title(it["caption"]) if it["caption"] else it["label"]
        title = f"{it['short']} $\\cdot$ {tex(title_short)}"
        rules.append([f"{it['short']}: {title_short}", rf"^{re.escape(it['short'])} ·"])
        # the item image
        if it["fig"]:
            img = figure_png(it, mi, img_dir)
        elif it["pi"] is not None:
            rect = table_region(paper, it["pi"], it["cap_block"])
            img = table_png(paper, it["pi"], rect, os.path.join(img_dir, f"{tag}.png"))
        else:
            img = None
        left = rf"\panel{{{img}}}" if img else r"\textcolor{gray}{(image not found)}"
        code = [(links[k]["name"], links[k]["url"]) for k in (mi or {}).get("code", [])]
        if mi:
            code = [("plotting / table script", file_link(man, sha, mi["script"]))] + code
            facts, desc = results.get((it["label"], None), ({}, None))
            right = right_col("", desc, facts, code)
        else:
            right = right_col(it["caption"][:300], None,
                              {"source": "published figure / table, not regenerated by the 2026 campaign"}, [])
        slides.append(frame(title, left, right, src=f"experiments/paper/main.pdf p. {it['page']}"))
        if not mi:
            continue
        # one slide per panel (figures with a panel file)
        pj = os.path.join(PAPER, (mi.get("figure") or "") + ".panels.json")
        if it["fig"] and mi.get("figure") and os.path.exists(pj):
            for L, p in json.load(open(pj)).items():
                crop = crop_panel(img, p["box"], os.path.join(img_dir, f"{tag}_panel_{L}.png"))
                m = EXP.metrics_of(p["run"]) or {} if p.get("run") else {}
                keys = ("one_step_r", "rollout_r", "Wij_R2", "Wij_slope", "tau_R2", "V_rest_R2", "msg_i_R2",
                        "msg_ij_R2", "clustering_accuracy", "stimuli_r_cell")
                facts = {"run": p.get("run") or ""}
                facts.update({k: m[k] for k in keys if k in m})
                slides.append(frame(f"{it['short']} $\\cdot$ panel {L}", rf"\panel{{{crop}}}",
                                    right_col(f"panel {L}", None, facts,
                                              [("plotting script", file_link(man, sha, mi["script"]))]),
                                    src=f"{mi['figure']}.panels.json"))
        # one slide per table section, then one metrics page per section
        bands = (section_bands(paper, it["pi"], table_region(paper, it["pi"], it["cap_block"]), mi.get("sections", []))
                 if not it["fig"] and it["pi"] is not None else [None] * len(mi.get("sections", [])))
        for s, band in zip(mi.get("sections", []), bands):
            stag = re.sub(r"\W+", "_", s["name"])
            if not it["fig"] and it["pi"] is not None:
                rect = table_region(paper, it["pi"], it["cap_block"])
                simg = table_png(paper, it["pi"], rect, os.path.join(img_dir, f"{tag}_{stag}.png"), highlight=band)
                facts, desc = results.get((it["label"], s["name"]), (section_facts(s), None))
                slides.append(frame(f"{it['short']} $\\cdot$ {tex(s['name'])}", rf"\panel{{{simg}}}",
                                    right_col(s["name"], desc, facts, code[:1]), src=mi["script"]))
            if not s.get("experiment"):
                continue
            head, rows = select_rows(s)
            rp = report_page(report, s["experiment"])
            right = ""
            if rp is not None:
                rimg = os.path.join(img_dir, f"report_exp{s['experiment']:02d}.png")
                if not os.path.exists(rimg) or os.path.getmtime(rimg) < os.path.getmtime(os.path.join(EXP_DIR, "report.pdf")):
                    report[rp].get_pixmap(dpi=200).save(rimg)
                right = (rf"{{\tiny\textcolor{{gray}}{{experiments/report.pdf, slide {rp + 1}}}}}\\[2pt]"
                         + rf"\includegraphics[width=\linewidth]{{{rimg}}}")
            left = (rf"{{\scriptsize\textbf{{experiment {s['experiment']}: landed rows}}}}\\[3pt]"
                    + (metrics_table_tex(head, rows) if rows else r"\textcolor{gray}{no landed row}")
                    + r"\\[4pt]{\tiny\textcolor{gray}{mean $\pm$ SD over folds; parentheses: \% outliers (R$^2$), "
                      r"\% values at the $\pm$100\,V limit (fit roll)}}")
            body = left + r"\\[8pt]" + (right.replace(r"width=\linewidth", r"height=0.42\textheight") if right else "")
            slides.append(frame_one(f"{it['short']} $\\cdot$ {tex(s['name'])} $\\cdot$ metrics", body,
                                    src=os.path.relpath(EXP.exp_path(s["experiment"]), ROOT)))
    if problems:
        slides.insert(0, frame("build warnings", r"\scriptsize " + r"\\ ".join(tex(p) for p in problems), ""))
    open(os.path.join(OUT, "slides", "all.tex"), "w").write("\n".join(slides))
    open(os.path.join(OUT, "deck.tex"), "w").write(PREAMBLE)
    env = dict(os.environ, TEXINPUTS=".:" + os.path.join(ROOT, "presentation") + "//:")
    for _ in range(2):
        r = subprocess.run(["pdflatex", "-interaction=nonstopmode", "deck.tex"], cwd=OUT, env=env,
                           capture_output=True, text=True)
    errs = re.findall(r"^! .*", open(os.path.join(OUT, "deck.log"), errors="replace").read(), re.M)
    if errs or not os.path.exists(os.path.join(OUT, "deck.pdf")):
        raise SystemExit("pdflatex failed:\n" + "\n".join(errs[:10]))
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import deck_site
    deck_site.build(os.path.join(OUT, "deck.pdf"), out=os.path.join(OUT, "site"),
                    title="GNN circuit models: paper figures and tables", rules=rules,
                    min_sections=1, max_sections=200)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--only", default=None, help="comma-separated item labels, e.g. tab:cv_gnn_vs_baselines")
    ap.add_argument("--force", action="store_true", help="build although the sync reports stale inputs")
    ap.add_argument("--no-agent", action="store_true", help="no claude call; cached descriptions only")
    a = ap.parse_args()
    build(set(a.only.split(",")) if a.only else None, a.force, not a.no_agent)
