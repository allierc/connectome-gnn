def figure_png(item, manifest_item, img_dir):
    if manifest_item and manifest_item.get("figure"):
        return os.path.join(PAPER, manifest_item["figure"] + ".png")
    f = os.path.join(PAPER, item["files"][0]) if item["files"] else None
    if f is None or not os.path.exists(f):
        return None
    if f.lower().endswith(".png"):
        return f
    import fitz
    out = os.path.join(img_dir, re.sub(r"\W+", "_", item["label"]) + "_fig.png")
    if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(f):
        fitz.open(f)[0].get_pixmap(dpi=200).save(out)
    return out


def table_region(doc, pi, cap_block):
    """The table under its caption on page pi: from the caption's top to the lowest horizontal rule before the
    next caption (booktabs' bottomrule), full text width."""
    import fitz
    pg = doc[pi]
    cap_y0, cap_y1 = cap_block[1], cap_block[3]
    nxt = pg.rect.height
    for b in pg.get_text("blocks"):
        if b[1] > cap_y1 + 2 and re.match(r"^(Supplementary )?(Table|Figure) \d+:", " ".join(b[4].split())):
            nxt = min(nxt, b[1])
    rules = [d["rect"] for d in pg.get_drawings()
             if d["rect"].height < 2 and d["rect"].width > 150 and cap_y1 < d["rect"].y0 < nxt]
    bottom = max((r.y1 for r in rules), default=min(nxt, cap_y1 + 200))
    x0 = min([r.x0 for r in rules] + [cap_block[0]]) - 2
    x1 = max([r.x1 for r in rules] + [cap_block[2]]) + 2
    return fitz.Rect(x0, cap_y0 - 2, x1, bottom + 3)


def table_png(doc, pi, rect, out, highlight=None):
    """Crop rect from page pi at 260 dpi; `highlight` = (y0, y1) in page units, drawn as a translucent band."""
    import fitz
    from PIL import Image, ImageDraw
    pix = doc[pi].get_pixmap(dpi=260, clip=rect)
    pix.save(out)
    if highlight:
        im = Image.open(out).convert("RGBA")
        sc = im.height / rect.height
        ov = Image.new("RGBA", im.size, (0, 0, 0, 0))
        ImageDraw.Draw(ov).rectangle([0, (highlight[0] - rect.y0) * sc, im.width, (highlight[1] - rect.y0) * sc],
                                     fill=(46, 160, 60, 85), outline=(30, 140, 45, 255), width=5)
        Image.alpha_composite(im, ov).convert("RGB").save(out)
    return out


def section_bands(doc, pi, rect, sections):
    """(y0, y1) of each section's rows inside the table rect: from its anchor text to the next section's anchor."""
    pg = doc[pi]
    ys = []
    for s in sections:
        hit = None
        if s.get("anchor"):
            hits = [r for r in pg.search_for(s["anchor"]) if rect.y0 + 25 < r.y0 < rect.y1 and r.x0 < rect.x0 + 140]
            hit = hits[0].y0 if hits else None
        ys.append(hit)
    bands = []
    for k, y in enumerate(ys):
        if y is None:
            bands.append(None)
            continue
        nxt = next((v for v in ys[k + 1:] if v is not None and v > y), rect.y1 - 3)
        bands.append((y - 1.5, nxt - 1.0))
    return bands


def crop_panel(png, box, out):
    from PIL import Image
    im = Image.open(png)
    W, H = im.size
    x0, y0, x1, y1 = box
    im.crop((int(max(0, x0 - 0.004) * W), int(max(0, y0 - 0.03) * H),
             int(min(1, x1 + 0.006) * W), int(min(1, y1 + 0.008) * H))).save(out)
    return out


def report_page(report_doc, n):
    """Index of the first slide of experiment n in report.pdf ("Experiment n --- ...")."""
    for pi in range(report_doc.page_count):
        t = report_doc[pi].get_text().split("\n", 1)[0]
        if re.match(rf"^Experiment {n}\b", t):
            return pi
    return None


# --------------------------------------------------------------------------- 4. GitHub permalinks
def permalinks(man):
    gh, branch = man["github"], man.get("branch", "main")
    sha = subprocess.run(["git", "-C", ROOT, "rev-parse", f"origin/{branch}"], capture_output=True, text=True).stdout.strip()
    links = {}
    for key, c in man["code"].items():
        txt = subprocess.run(["git", "-C", ROOT, "show", f"{sha}:{c['file']}"], capture_output=True, text=True)
        n = None
        if txt.returncode == 0:
            for i, line in enumerate(txt.stdout.split("\n"), 1):
                if re.search(c["find"], line):
                    n = i
                    break
        links[key] = {"name": c["name"], "url": f"{gh}/blob/{sha}/{c['file']}" + (f"#L{n}" if n else ""),
                      "pushed": txt.returncode == 0}
    return sha, links


def file_link(man, sha, rel):
    return f"{man['github']}/blob/{sha}/{rel}"


