def param_table_tex(columns):
    """columns = [(header, run)]: the runs' settings and every regulariser coefficient that is nonzero in any of
    them, one column per run, read from <run>/config.yaml."""
    cfgs = [(h, run_config(r) if r else {}) for h, r in columns]
    cfgs = [(h, c) for h, c in cfgs if c]
    if not cfgs:
        return ""
    rows = []
    for lab, get in PARAM_ROWS:
        vals = []
        for _h, c in cfgs:
            try:
                v = get(c)
            except Exception:                                # noqa: BLE001 -- a missing block is a blank cell
                v = None
            vals.append("" if v in (None, "None x None") else v)
        if any(str(v) != "" for v in vals):
            rows.append((lab, vals))
    coeffs = sorted({k for _h, c in cfgs for k, v in (c.get("training") or {}).items()
                     if k.startswith("coeff_") and v not in (0, 0.0, None, False)})
    for k in coeffs:
        rows.append((k[len("coeff_"):], [(c.get("training") or {}).get(k, 0) for _h, c in cfgs]))
    head = r"\textcolor{gray}{parameter} & " + " & ".join(rf"\textbf{{{tex(h)}}}" for h, _ in cfgs) + r" \\ \hline"
    body = "\n".join(rf"\textcolor{{gray}}{{{tex(l)}}} & " + " & ".join(tex(v) for v in vals) + r" \\"
                     for l, vals in rows)
    return (r"\resizebox{\linewidth}{!}{\fontsize{6}{7}\selectfont\setlength{\tabcolsep}{3pt}\begin{tabular}{l"
            + "l" * len(cfgs) + "}" + head + "\n" + body + r"\end{tabular}}")


def section_points(sec):
    fm, _ = EXP.load(EXP.exp_path(sec["experiment"]))
    arms = sec.get("arm")
    arms = [arms] if isinstance(arms, str) else (arms or [])
    return fm, [(a, pt, r) for a, pt, r in EXP.runs(fm)
                if (not arms or a["id"] in arms)
                and all(pt.get(ax) in vals for ax, vals in (sec.get("cells") or {}).items())]


def section_columns(sec):
    """One column per (arm, grid cell) of the section, the first landed fold's run."""
    if not sec.get("experiment"):
        return []
    fm, pts = section_points(sec)
    several_arms = len({a["id"] for a, _p, _r in pts}) > 1
    cols, seen = [], set()
    for a, pt, r in pts:
        key = (a["id"],) + tuple(v for k, v in pt.items() if k != "fold")
        if key in seen or EXP.metrics_of(r) is None:
            continue
        seen.add(key)
        lab = " ".join(([a["id"]] if several_arms else []) + [str(v) for k, v in pt.items() if k != "fold"])
        cols.append((lab or a["id"], r))
    return cols


def item_columns(mi):
    """One column per section that has an experiment (its first landed run); one column per cell when the item
    has a single section."""
    secs = [sc for sc in mi.get("sections", []) if sc.get("experiment")]
    if len(secs) == 1:
        return section_columns(secs[0])
    out = []
    for sc in secs:
        c = section_columns(sc)
        if c:
            out.append((sc["name"], c[0][1]))
    return out


def item_facts(mi):
    """An item's own facts: its single section's, or one line per section naming its experiment."""
    secs = mi.get("sections", [])
    if len(secs) == 1:
        return section_facts(secs[0])
    out = {}
    for sc in secs:
        if sc.get("experiment"):
            fm, _ = EXP.load(EXP.exp_path(sc["experiment"]))
            out[sc["name"]] = f"experiment {fm['number']}: {(fm.get('report') or {}).get('slide_title') or fm['name']}"
        else:
            out[sc["name"]] = "published values"
    return out


def section_facts(sec):
    if not sec.get("experiment"):
        return {"source": "published values (not regenerated by the campaign)"}
    fm, _ = EXP.load(EXP.exp_path(sec["experiment"]))
    runs = section_runs(sec)
    landed = [r for r in runs if EXP.metrics_of(r) is not None]
    f = {"experiment": f"{fm['number']}: {(fm.get('report') or {}).get('slide_title') or fm['name']}",
         "arm": ", ".join([sec["arm"]] if isinstance(sec.get("arm"), str) else (sec.get("arm") or ["all"])),
         "runs": f"{len(landed)} of {len(runs)} landed"}
    return f


