def landed_rows(n):
    """The experiment file's landed table: [{column: cell}]."""
    body = open(EXP.exp_path(n)).read()
    m = re.search(r"### Landed[^\n]*\n\n(\|.*?)\n\n", body, re.S)
    if not m:
        return [], []
    lines = [l for l in m.group(1).split("\n") if l.startswith("|")]
    head = [c.strip() for c in lines[0].strip("|").split("|")]
    rows = [dict(zip(head, [c.strip() for c in l.strip("|").split("|")])) for l in lines[2:]]
    return head, rows


def select_rows(sec):
    head, rows = landed_rows(sec["experiment"])
    arms = sec.get("arm")
    arms = [arms] if isinstance(arms, str) else (arms or [])
    out = []
    for r in rows:
        if arms and r.get("arm") not in arms:
            continue
        if any(r.get(ax) not in vals for ax, vals in (sec.get("cells") or {}).items()):
            continue
        out.append(r)
    return head, out


