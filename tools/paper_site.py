ROLE = """You write the description shown beside a figure or table of a scientific paper on a slide.
Input: a caption and a list of facts (experiment, model, trainer settings, data, runs).
Output: JSON only, {"description": "<text>"}, the text at most 70 words, 2 to 4 sentences.
Rules: every sentence is a definition, a parameter with its value, a method step, or a number given in the input.
Use only the input. No interpretation, no evaluation, no adjectives such as good, strong, clear, faithful, robust,
no narrative words such as notably, thus, so, importantly, demonstrates, highlights. Name quantities with their units.
Say what was trained, on which data, and what is plotted or tabulated.
Identifiers (dataset, run, arm and model names) are codes: quote them verbatim or leave them out, and never
explain them except with the GLOSSARY given in the input. Every number you write must appear in the input."""

GLOSSARY = """GLOSSARY (meaning of identifier fragments; use only these):
- blank50: in every video clip of the stimulus, the first 50% of the frames are replaced by blank frames
- cv00 .. cv04: cross-validation folds 0 to 4
- noise_free / noise_005 / noise_05: model noise sigma 0 / 0.05 / 0.5
- 010 / 020 after noise_005: measurement noise gamma 0.1 / 0.2
- flyvis_conductance: code name of the general-form GNN, g_phi = MLP(a_i, a_j, v_i, v_j)
- flyvis_known_ode: code name of the Known-ODE model (the generator's equation with learned W, tau, V_rest)
- condl25 / condl100: group lasso 25 / 100 on g_phi's input groups
- null_edges_pc_400 / null400: 400% extra null edges added to the connectome
- removed_pc_20 / rm20, removed_pc_50 / rm50: 20% / 50% of the edges removed
- hidden_020 / hid20, hid10: 20% / 10% of the neurons hidden
- s5h06 / s5h21: one frame in five observed, rollout horizon 6 / 21
- INR_davis: stimulus not given, learned by a SIREN network
- full_eye_flywireRF / e8_flywireRF: FlyWire eye / e8 hybrid connectome; proximal_nulls: with proximal null edges"""

BANNED = ("notably", "importantly", "demonstrat", "highlight", "robust", "faithful", "clear", "strong", "excellent",
          "remarkabl", "impressive", "successfully", "thus", "therefore", "suggest", "indicat", "reveal")


def _numbers(t):
    return {x.lstrip("0") or "0" for x in re.findall(r"\d+(?:\.\d+)?", t.replace(",", ""))}


def _valid(desc, text):
    """A description passes if every number in it occurs in its input and it has no banned word."""
    low = desc.lower()
    if any(w in low for w in BANNED):
        return False
    return _numbers(desc) <= _numbers(text) | {"1", "2", "3", "4", "5"}


def describe(caption, facts, use_agent=True):
    text = ("CAPTION: " + caption[:900] + "\nFACTS:\n" + "\n".join(f"- {k}: {v}" for k, v in facts.items())
            + "\n" + GLOSSARY)
    key = hashlib.sha1(f"{PROMPT_VERSION}|{MODEL}|{text}".encode()).hexdigest()[:16]
    os.makedirs(CACHE, exist_ok=True)
    cp = os.path.join(CACHE, f"desc_{key}.json")
    if os.path.exists(cp):
        return json.load(open(cp)).get("description")
    if not use_agent or not shutil.which("claude"):
        return None
    d = None
    for _attempt in range(2):                         # one retry: a malformed JSON answer happens
      try:
        r = subprocess.run(["claude", "-p", text, "--append-system-prompt", ROLE, "--model", MODEL,
                            "--effort", "low", "--allowedTools", ""],
                           capture_output=True, text=True, timeout=150, stdin=subprocess.DEVNULL)
        m = re.search(r"\{.*\}", r.stdout, re.S)
        d = json.loads(m.group(0))["description"] if m else None
        if d and not _valid(d, text):
            print("agent description rejected (a number not in the facts, or a banned word):", d[:120])
            d = None
        break
      except Exception as e:                                 # noqa: BLE001 -- the slide keeps its facts
        print("agent failed:", type(e).__name__, e)
        d = None
    if d:
        json.dump({"description": d, "facts": text, "model": MODEL, "prompt_version": PROMPT_VERSION},
                  open(cp, "w"), indent=1)
    return d


