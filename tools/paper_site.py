def landed_rows(n):
    """The experiment file's landed table: [{column: cell}]."""
    body = open(EXP.exp_path(n)).read()
    m = re.search(r"### Landed[^\n]*\n\n(\|.*?)\n\n", body, re.S)
    if not m:
        return [], []
    lines = [l for l in m.group(1).split("\n") if l.startswith("|")]
    head = [c.strip() for c in lines[0].strip("|").split("|")]
    rows = [dict(zip(head, [c.strip() for c in l.strip("|").split("|")])) for l in lines[2:]]
    return head, rows


def select_rows(sec):
    head, rows = landed_rows(sec["experiment"])
    arms = sec.get("arm")
    arms = [arms] if isinstance(arms, str) else (arms or [])
    out = []
    for r in rows:
        if arms and r.get("arm") not in arms:
            continue
        if any(r.get(ax) not in vals for ax, vals in (sec.get("cells") or {}).items()):
            continue
        out.append(r)
    return head, out


def section_runs(sec):
    fm, _ = EXP.load(EXP.exp_path(sec["experiment"]))
    arms = sec.get("arm")
    arms = [arms] if isinstance(arms, str) else (arms or [])
    return [r for a, pt, r in EXP.runs(fm)
            if (not arms or a["id"] in arms)
            and all(pt.get(ax) in vals for ax, vals in (sec.get("cells") or {}).items())]


def run_config(run):
    p = os.path.join(LOG_ROOT, run, "config.yaml")
    return yaml.safe_load(open(p)) if os.path.exists(p) else {}


def config_facts(cfg):
    sim, gm, tr = cfg.get("simulation", {}), cfg.get("graph_model", {}), cfg.get("training", {})
    sched = tr.get("rollout_horizon_schedule") or []
    f = {"dataset": cfg.get("dataset"),
         "model": gm.get("signal_model_name"),
         "g_phi input size": gm.get("input_size"), "embedding dim": gm.get("embedding_dim"),
         "MLP hidden": gm.get("hidden_dim"),
         "model noise sigma": sim.get("noise_model_level"),
         "measurement noise gamma": sim.get("measurement_noise_level"),
         "epochs": tr.get("n_epochs"), "batch": tr.get("batch_size"),
         "data augmentation loop": tr.get("data_augmentation_loop"),
         "lr / lr_W / lr_embedding": f"{tr.get('lr')} / {tr.get('lr_W')} / {tr.get('lr_embedding')}",
         "training": ("recurrent, horizon " + (f"{sched[0]} to {sched[-1]}" if sched else "")
                      if tr.get("recurrent_training") else "one-step"),
         "MLP precision": tr.get("mlp_precision", "fp32")}
    main = ("W_L1", "W_L2", "g_phi_input_group_L1", "g_phi_weight_L1", "f_theta_weight_L1")
    regs = {k: tr.get("coeff_" + k) for k in main if tr.get("coeff_" + k) not in (0, 0.0, None, False)}
    f["regularisers"] = ", ".join(f"{k} {v}" for k, v in regs.items())
    f.pop("g_phi input size", None); f.pop("MLP hidden", None); f.pop("lr / lr_W / lr_embedding", None)
    return {k: v for k, v in f.items() if v not in (None, "", "None / None / None")}


def item_facts(mi):
    """An item's own facts: its single section's, or one line per section naming its experiment."""
    secs = mi.get("sections", [])
    if len(secs) == 1:
        return section_facts(secs[0])
    out = {}
    for sc in secs:
        if sc.get("experiment"):
            fm, _ = EXP.load(EXP.exp_path(sc["experiment"]))
            out[sc["name"]] = f"experiment {fm['number']}: {(fm.get('report') or {}).get('slide_title') or fm['name']}"
        else:
            out[sc["name"]] = "published values"
    return out


def section_facts(sec):
    if not sec.get("experiment"):
        return {"source": "published values (not regenerated by the campaign)"}
    fm, _ = EXP.load(EXP.exp_path(sec["experiment"]))
    runs = section_runs(sec)
    landed = [r for r in runs if EXP.metrics_of(r) is not None]
    f = {"experiment": f"{fm['number']}: {(fm.get('report') or {}).get('slide_title') or fm['name']}",
         "arm": ", ".join([sec["arm"]] if isinstance(sec.get("arm"), str) else (sec.get("arm") or ["all"])),
         "runs": f"{len(landed)} of {len(runs)} landed"}
    # the grid the section covers, every axis but the fold (several values: the config below is the first run's)
    axes = {k: v for k, v in fm["axes"].items() if k != "fold"}
    if sec.get("cells"):
        axes.update(sec["cells"])
    if axes:
        f["cells"] = "; ".join(f"{k}: {', '.join(map(str, v))}" for k, v in axes.items())
    if landed:
        f.update(config_facts(run_config(landed[0])))
    return f


