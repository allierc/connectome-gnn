def short_title(caption, n=34):
    """The caption's first sentence, cut at a word boundary to fit one title line."""
    t = caption.split(". ")[0].rstrip(".")
    if len(t) <= n:
        return t
    return t[:n].rsplit(" ", 1)[0] + " ..."


def check_sync(experiments, used_runs, force):
    p = os.path.join(EXP_DIR, "sync_status.json")
    if not os.path.exists(p):
        raise SystemExit("no experiments/sync_status.json: run `python tools/exp.py sync` first")
    st = json.load(open(p))
    t_sync = time.mktime(time.strptime(st["time"], "%Y-%m-%d %H:%M:%S"))
    problems = []
    for n in sorted(experiments):
        path = EXP.exp_path(n)
        if os.path.getmtime(path) > t_sync + 120:
            problems.append(f"exp{n:02d}: {os.path.basename(path)} changed after the sync of {st['time']}")
        e = st["experiments"].get(str(n)) or st["experiments"].get(n)
        if e is None:
            problems.append(f"exp{n:02d}: not in the sync")
        else:
            owed = sorted(set(e["trained_not_analysed"]) & used_runs)
            if owed:
                problems.append(f"exp{n:02d}: {len(owed)} runs the paper uses are trained but not analysed "
                                f"({owed[0]} ...)")
    if problems and not force:
        raise SystemExit("inputs not up to date (run `python tools/exp.py sync [--submit-analyses]`, or --force):\n  "
                         + "\n  ".join(problems))
    for q in problems:
        print("WARNING", q)
    return st, problems


