def n_tex(v):
    return f"{v:,}".replace(",", "{,}")


def frames_of(run, *rel):
    """The tester's rollout length for `run` ("Frames evaluated" of its log)."""
    return n_tex(tester_rollout_frames(os.path.join(LOG_ROOT, run, *(rel or ("results_rollout.log",)))))


def fitted_pct(run):
    """Percent of the run's edges the template readout fitted: metrics Wij_n over simulation.n_edges."""
    n_edges = yaml.safe_load(open(os.path.join(LOG_ROOT, run, "config.yaml")))["simulation"]["n_edges"]
    return f"${round(100 * read_metrics(os.path.join(LOG_ROOT, run))['Wij_n'] / n_edges)}\\%$"


