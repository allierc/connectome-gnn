def red_section(heading, next_heading):
    """Red from the line after `heading` (and its \\label) to `next_heading`, heading itself black."""
    global tex
    once(tex, heading); once(tex, next_heading)
    i = tex.index(heading) + len(heading)
    i = tex.index("\n", i) + 1
    if tex[i:].lstrip(" ").startswith("\\label"):
        i = tex.index("\n", i) + 1
    j = tex.index(next_heading, i)
    tex = tex[:i] + RED_OPEN + tex[i:j].rstrip("\n") + "\n" + RED_CLOSE + "\n" + tex[j:]


